export function namasteDevDocs() {
  const docs = [];
  let slNo = 0;
  NAMASTE_DEV_INDEX.forEach((group, sectionOrder) => {
    group.videos.forEach(([title, duration]) => {
      slNo += 1;
      docs.push({
        courseSlug: NAMASTE_DEV_SLUG,
        section: group.section,
        sectionOrder,
        slNo,
        title,
        durationSeconds: parseDuration(duration),
      });
    });
  });
  return docs;
}
