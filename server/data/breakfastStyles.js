const NOTE =
  "Kerala kitchen only: coconut oil, mustard, curry leaves, chilli. No dosa, idli, sambar, curd, milk, juice, or sugar in tea. Weigh dry/raw grams. Eat protein and vegetables first, starch last.";

function tadka() {
  return "Heat 1–2 tsp coconut oil. Add 1/4 tsp mustard. When it pops, add 1 sprig curry leaves, 1 green chilli (slit), and 40 g sliced onion. Fry 1 minute.";
}

function chapati(g) {
  return [
    `Mix ${g} g atta with a pinch of salt and a few teaspoons of water into a soft dough. Rest 5 minutes.`,
    "Roll ONE thin chapati. Cook on a hot dry tawa until brown spots appear, about 30–40 seconds a side. Do not make a second roti.",
  ];
}

function ragiRoti(g) {
  return [
    `Mix ${g} g ragi flour with a pinch of salt and hot water to a soft dough. Rest 3 minutes.`,
    "Pat or roll ONE thin roti. Cook on a tawa with a drop of coconut oil until cooked through. One roti only.",
  ];
}

function plate({
  name,
  style,
  slots = ["morning"],
  weigh,
  prep = ["Chop all vegetables before you light the stove."],
  cook,
  carbs,
  fiberG,
  proteinG,
  fatG,
}) {
  const [low, high] = carbs;
  return {
    name,
    style,
    slots,
    carbsG: high,
    fiberG,
    proteinG,
    fatG,
    sugarNote: `${NOTE} Logged carbs use the top of the range (${low}–${high} g) so the diary does not under-count.`,
    instructions: [
      "WEIGH (raw / dry, before soaking or cooking)",
      ...weigh.map((line) => `• ${line}`),
      "",
      "PREP",
      ...prep.map((line, i) => `${i + 1}. ${line}`),
      "",
      "COOK",
      ...cook.map((line, i) => `${i + 1}. ${line}`),
      "",
      "PLATE",
      "1. Put egg, fish, chicken, thoran, or salad on the plate first.",
      "2. Add the weighed starch last (chapati, rice, oats, kadala, cherupayar).",
      "3. Stop when that starch is gone. No extra scoop, no second roti.",
    ].join("\n"),
  };
}

